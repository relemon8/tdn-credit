pub fn detail(n: &NewsItem) -> String {
    let mut text = n.detail.clone();
    for (from, to) in [
        ("Net leverage", "負債倍率"),
        ("Market spread shock", "市場への上乗せ幅の衝撃"),
        ("Market shock", "市場への上乗せ幅の衝撃"),
        ("Risk appetite", "リスク選好"),
        ("Market liquidity", "市場の売買のしやすさ"),
        ("Liquidity", "売買のしやすさ"),
        ("5Y Treasury", "5年国債金利"),
        ("非Default", "未破綻"),
        ("Spread", "上乗せ幅"),
        ("Price", "価格"),
        ("Debt", "有利子負債"),
        ("FCF", "自由に使える現金"),
        (" close:", " 月末："),
        ("Recovery", "回収率"),
        ("Cash", "現金"),
        ("Default", "破綻"),
        ("Agency", "格付け会社"),
        ("Rating", "格付け"),
    ] {
        text = text.replace(from, to);
    }
    text
}

